#!/usr/bin/env python3
"""Voice clips -> word times on the film timeline -> src/cues.ts and audio/voice.wav (lesson L010/L046: one clock for everything).
Whisper (whisper-cli, ggml-small.en) times every spoken word; each clip's dead air is trimmed; clips are placed with fixed gaps.
Run from projects/kyani-co-marine-lines:  python3 timing.py"""
import json, os, re, subprocess, difflib

MODEL = os.path.expanduser("~/.cache/hyperframes/whisper/models/ggml-base.en.bin")
LINES = json.load(open("voice_lines.json"))
SCENE = {"v1": 0.2, "v2": 4.2, "v3": 8.0, "v4": 14.0}   # user chose 15-20 s; food scene holds the 3 items
START = 0.35                                                       # first clip starts here
HOLD = 3.0                                                         # end card held after the last word (L036/L034)
os.makedirs("audio", exist_ok=True); os.makedirs("work", exist_ok=True)

def norm(w): return re.sub(r"[^a-z0-9']", "", w.lower().replace("&", "and"))
def script_words(text): return [w for w in re.findall(r"[A-Za-z0-9'&]+", text)]

def whisper(path):
    wav = f"work/{os.path.basename(path)}.16k.wav"
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", path, "-ac", "1", "-ar", "16000", wav], check=True)
    base = wav + ".w"
    subprocess.run(["whisper-cli", "-m", MODEL, "-f", wav, "-ml", "1", "-sow", "-oj", "-of", base], capture_output=True, check=True)
    j = json.load(open(base + ".json")); out = []
    for seg in j["transcription"]:
        t = seg["text"].strip()
        if not norm(t) or t.startswith("["): continue
        out.append({"w": t, "t0": seg["offsets"]["from"] / 1000, "t1": seg["offsets"]["to"] / 1000})
    return out

clips, t = {}, START
order = list(LINES)
for k in order:
    src = f"voice/{k}.wav"
    dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]).decode())
    ws = whisper(src)
    first = max(0.0, (ws[0]["t0"] if ws else 0) - 0.04)           # trim dead air before the first word
    t = SCENE[k]
    # align whisper tokens to the script words (whisper may merge/split: map by sequence match)
    sw = script_words(LINES[k]); a = [norm(x["w"]) for x in ws]; b = [norm(x) for x in sw]
    sm = difflib.SequenceMatcher(None, a, b); words = []
    matched = {j: i for blk in sm.get_matching_blocks() for i, j in zip(range(blk.a, blk.a + blk.size), range(blk.b, blk.b + blk.size))}
    for j, word in enumerate(sw):
        i = matched.get(j)
        if i is None:   # unmatched script word (e.g. spelled phonetically for the voice): borrow the neighbour's time
            i = min(max(j, 0), len(ws) - 1)
        words.append({"w": word, "t0": round(t + ws[i]["t0"] - first, 3), "t1": round(t + ws[i]["t1"] - first, 3), "exact": j in matched})
    end = t + (ws[-1]["t1"] - first if ws else dur - first)
    clips[k] = {"start": round(t, 3), "end": round(end, 3), "trim": round(first, 3), "words": words}
    t = end
total = round(t + HOLD, 3)

# voice track on the film timeline
ins, fl, lab = [], [], []
for i, k in enumerate(order):
    c = clips[k]; ins += ["-i", f"voice/{k}.wav"]; ms = int(c["start"] * 1000)
    fl.append(f"[{i}:a]atrim=start={c['trim']},asetpts=PTS-STARTPTS,adelay={ms}|{ms},apad=whole_dur={total}[v{i}]"); lab.append(f"[v{i}]")
fc = ";".join(fl) + ";" + "".join(lab) + f"amix=inputs={len(order)}:normalize=0,pan=stereo|c0=c0|c1=c0,loudnorm=I=-15:TP=-1.5:LRA=7[out]"
subprocess.run(["ffmpeg", "-v", "error", "-y", *ins, "-filter_complex", fc, "-map", "[out]", "-t", str(total), "-ar", "44100", "audio/voice.wav"], check=True)

os.makedirs("src", exist_ok=True)
open("src/cues.ts", "w").write("// generated by timing.py from whisper word times; every caption and animation reads these (L046). Do not edit.\n"
    + "export const TOTAL = " + str(total) + ";\nexport const CLIPS = " + json.dumps(clips, indent=1) + " as Record<string, { start: number; end: number; trim: number; words: { w: string; t0: number; t1: number; exact: boolean }[] }>;\n")
json.dump({"total": total, "clips": clips}, open("data_timing.json", "w"), indent=1)
for k, c in clips.items(): print(k, c["start"], "->", c["end"], " ".join(f"{w['w']}@{w['t0']}" for w in c["words"]), "| unmatched:", [w["w"] for w in c["words"] if not w["exact"]])
print("total", total)
